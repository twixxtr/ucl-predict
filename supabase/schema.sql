-- Run in Supabase Dashboard > SQL Editor.
-- This creates student profiles, predictions, match result storage and a leaderboard view.

-- 1. Student Profiles Table (linked to Supabase auth.users for anonymous auth)
create table if not exists public.student_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null check (char_length(trim(full_name)) between 1 and 60),
  department text not null check (department in ('CSE', 'ECE', 'EEE', 'ME', 'CE', 'Other')),
  year text not null check (year in ('1st Year', '2nd Year', '3rd Year', '4th Year')),
  class_division text not null check (char_length(trim(class_division)) between 1 and 20),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Legacy profiles table preserved for backwards compatibility
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 60),
  created_at timestamptz not null default now()
);

-- 2. Matches Table
create table if not exists public.matches (
  id text primary key,
  home_team text not null,
  away_team text not null,
  kickoff_at timestamptz,
  actual_home integer check (actual_home between 0 and 20),
  actual_away integer check (actual_away between 0 and 20),
  result_confirmed boolean not null default false,
  created_at timestamptz not null default now()
);

